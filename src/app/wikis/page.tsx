import Link from "next/link";
import { connection } from "next/server";
import { Suspense } from "react";
import { listPublicWikis } from "@/lib/wiki-store";

export const metadata = { title: "Public wikis — Shadow", description: "Explore public codebase documentation generated by Shadow." };

async function PublicWikisContent() {
  await connection();
  const wikis = await listPublicWikis(100);
  return (
    <main className="mx-auto min-h-screen max-w-6xl px-4 py-12">
      <header className="mb-8">
        <Link href="/" className="text-sm text-muted-foreground hover:text-foreground">← Shadow</Link>
        <h1 className="mt-4 text-3xl font-semibold tracking-tight">Recent public wikis</h1>
        <p className="mt-2 text-muted-foreground">Browse documentation generated from public repositories.</p>
      </header>
      {wikis.length ? (
        <ul className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {wikis.map((wiki) => (
            <li key={`${wiki.owner}/${wiki.name}`}>
              <Link href={`/wiki/${wiki.owner}/${wiki.name}`} className="block h-full rounded-xl border bg-card p-5 transition hover:border-foreground/30 hover:shadow-sm">
                <h2 className="font-medium">{wiki.owner}/{wiki.name}</h2>
                <p className="mt-2 line-clamp-2 min-h-10 text-sm text-muted-foreground">{wiki.description ?? "Public repository documentation"}</p>
                <p className="mt-4 text-xs text-muted-foreground">{wiki.pageCount} pages · {wiki.branch} · {wiki.sha.slice(0, 7)}</p>
              </Link>
            </li>
          ))}
        </ul>
      ) : <p className="rounded-xl border border-dashed p-8 text-sm text-muted-foreground">No public wikis yet.</p>}
    </main>
  );
}

export default function PublicWikisPage() {
  return (
    <Suspense fallback={<main className="mx-auto min-h-screen max-w-6xl animate-pulse px-4 py-12" />}>
      <PublicWikisContent />
    </Suspense>
  );
}
